import express from "express";
import cors from "cors";
import crypto from "crypto";
import pg from "pg";
import path from "node:path";

const { Pool } = pg;
const app = express();

app.use(cors());
app.use(express.json({ limit: "1mb" }));

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.DATABASE_URL
    ? { rejectUnauthorized: false }
    : false
});

// DASHBOARD
const dashboardPath = path.resolve("dashboard.html");

app.get(["/dashboard", "/dashboard.html"], (req, res) => {
  res.sendFile(dashboardPath, (error) => {
    if (error) {
      console.error("Dashboard error:", error);
      if (!res.headersSent) {
        res.status(404).send("Dashboard not found");
      }
    }
  });
});

async function initDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS api_keys (
      id SERIAL PRIMARY KEY,
      api_key TEXT UNIQUE NOT NULL,
      active BOOLEAN DEFAULT TRUE,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
  `);
}

async function checkApiKey(req) {
  const key =
    req.headers["x-api-key"] ||
    req.headers.authorization?.replace(/^Bearer\s+/i, "");

  if (!key || !key.startsWith("flash_")) return false;

  const result = await pool.query(
    "SELECT id FROM api_keys WHERE api_key = $1 AND active = TRUE",
    [key]
  );

  return result.rowCount > 0;
}

